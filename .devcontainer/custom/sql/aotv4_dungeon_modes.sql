-- ---------------------------------------------------------------- tasks
-- ⚠️ The cleanup DELETE names ONLY 2000300-2000359, the range this script itself creates. That rule
-- exists because aotv4_moonfire_line.sql once swept 43318-43323 -- six spells belonging to another
-- script -- with no error (§5). 2000359 is the top of the six mode families, not a round number.
DELETE FROM task_activities WHERE taskid BETWEEN 2000300 AND 2000359;
DELETE FROM tasks          WHERE id     BETWEEN 2000300 AND 2000359;

INSERT INTO tasks
  (id, type, duration, duration_code, title, description, reward_text, reward_id_list,
   cash_reward, exp_reward, reward_method, reward_points, min_level, max_level, level_spread,
   min_players, max_players, repeatable, faction_reward, completion_emote, enabled)
SELECT
    z.base + m.moff,
    0,
    m.dur,
    3,
    -- ⚠️ Standard carries NO mode suffix, so its title is byte-identical to what it has always been.
    -- The other five are tagged, because a player running three modes on one zone otherwise cannot
    -- tell which journal entry is which.
    CONCAT('Delve: ', z.zname, CASE WHEN m.moff = 0 THEN '' ELSE CONCAT(' (', m.mname, ')') END),
    z.descr,
    'A reward chest, and a Delver''s Sigil for your first delve', '', 0, 0, 0, 0,
    1, 200, 0, 1, 6, 1, 0,
    z.emote, 1
FROM tmp_delve_zone z CROSS JOIN tmp_delve_mode m;

-- ---------------------------------------------------------------- activity 0: the trash
-- ⚠️ AN EMPTY npc_match_list MATCHES EVERY NPC -- the mechanic, not an oversight
-- (task_client_state.cpp:528 wraps the whole name test in `if (!npc_match_list.empty() && ...)`).
-- ⚠️ `zones` is the BASE zone id; instances keep it, so one activity row serves every instance.
INSERT INTO task_activities
  (taskid, activityid, step, activitytype, target_name, goalmethod, goalcount,
   description_override, npc_match_list, item_id_list, zones, optional)
SELECT
    z.base + m.moff, 0, 1, 2, z.tgt, 0,
    -- ⚠️ GREATEST(...,1): Gauntlet's 0.34 multiplier must never round a zone down to a goal of zero,
    -- which would complete the trash step instantly and skip straight to the bosses.
    GREATEST(ROUND(z.goal * m.goalmul), 1),
    '', '', '', z.zoneid, 0
FROM tmp_delve_zone z CROSS JOIN tmp_delve_mode m;

-- ---------------------------------------------------------------- activity 1: the boss
-- ⚠️ step 2, so the task system only opens it once the trash goal is met -- that ordering is native
-- and is why no Lua is needed to gate the boss objective; Lua only has to SPAWN the thing, off
-- event_task_stage_complete for activity 0.
-- ⚠️ npc_match_list is the boss npc id as TEXT. It matches on npc_type id, which is why the boss has
-- to be one fixed row (see the boss note at the top).
-- ⚠️ No `zones` restriction needed beyond the same base zone id; the boss only ever exists inside a
-- delve instance because nothing else spawns it.
INSERT INTO task_activities
  (taskid, activityid, step, activitytype, target_name, goalmethod, goalcount,
   description_override, npc_match_list, item_id_list, zones, optional)
SELECT
    z.base + m.moff, 1, 2, 2,
    CASE WHEN m.bosses > 1 THEN 'the delve wardens' ELSE 'the delve warden' END,
    0, m.bosses,
    CASE WHEN m.bosses > 1
         THEN 'Defeat the wardens of the delve'
         ELSE 'Defeat the warden of the delve' END,
    '2000301', '', z.zoneid, 0
FROM tmp_delve_zone z CROSS JOIN tmp_delve_mode m;

DROP TEMPORARY TABLE tmp_delve_mode;
DROP TEMPORARY TABLE tmp_delve_zone;

-- ---------------------------------------------------------------- verify
