-- AoTv4 -- Delve difficulty MODES + the end-of-delve BOSS step.            2026-07-30
-- ============================================================================================
-- Adds six parallel difficulty modes over the same six Dragons of Norrath zones, and gives every
-- delve a second objective: once the trash goal is met, a boss appears and must be killed.
--
-- ⚠️⚠️ THIS SCRIPT OWNS EVERY DELVE TASK, 2000300-2000359 -- INCLUDING THE STANDARD FAMILY that
-- `aotv4_dungeon.sql` originally created. It supersedes the `tasks` / `task_activities` block in that
-- file, because the boss step has to be added to Standard too and split ownership between two scripts
-- would mean whichever ran last silently won. Run THIS one after it. The rest of aotv4_dungeon.sql
-- (the chest npc, the zone rows) is untouched and still owned there.
--
-- ⚠️⚠️ EACH MODE NEEDS ITS OWN TASK ROWS AND THAT IS NOT AVOIDABLE. `task_activities.goalcount` and
-- `tasks.duration` are STATIC COLUMNS -- nothing changes a kill target or a timer at runtime. A mode
-- that alters either can only be expressed as a different task row, so the task id is
-- `<zone base> + <mode offset>`:
--     +0  Standard    +10 Hard    +20 Swarm    +30 Gauntlet    +40 Onslaught    +50 Fragile
-- Keep those offsets in step with `M.MODES.taskoff` in lua_modules/aotv4_dungeon.lua -- a mismatch
-- means AssignTask silently targets a task that does not exist and the player gets no journal entry.
--
-- ⚠️ Tasks and activities are loaded by the ZONE at boot, not from shared memory, so this needs a
-- zone restart and NOT ./shared_memory. The boss npc_types row is the same -- zone restart only.
-- ============================================================================================

-- ---------------------------------------------------------------- the boss
-- ⚠️ ONE npc type, randomised at spawn by Lua -- not a pool of rows. `task_activities.npc_match_list`
-- is static, so the task can only match a fixed id; the variety has to come from what Lua does to the
-- spawned mob (name, appearance, stats), never from picking a different row.
--
-- ⚠️ THE NAME MUST KEEP ITS LEADING '#'. That is not decoration: the score sheet decides "named"
-- with the same heuristic as §17c and quest_difficulty.pl -- EQ trash is lowercase, named mobs are
-- proper nouns or lead with '#' -- and a named kill is worth 3x in M.kill_value. Rename it to
-- something lowercase and every boss silently scores as trash.
--
-- ⚠️ Cloned VIA A TEMP TABLE so all ~100 npc_types columns stay byte-identical to a real named mob.
-- Never hand-list the columns; that is how `aggro_spell_id` (which does not exist on this schema)
-- got into an earlier pass of aotv4_dungeon.sql.
DROP TEMPORARY TABLE IF EXISTS tmp_delve_boss;
CREATE TEMPORARY TABLE tmp_delve_boss AS SELECT * FROM npc_types WHERE id = 119170;

UPDATE tmp_delve_boss SET
    id          = 2000301,
    name        = '#a_delve_warden',
    lastname    = 'Delve Warden',
    level       = 1,          -- scaled at spawn; this is only a floor
    hp          = 1000,       -- ditto: ModifyNPCStat rewrites it per run
    size        = 8,
    runspeed    = 1.25,       -- faster than trash so it closes; not so fast it cannot be kited
    npc_faction_id = 0,
    loottable_id   = 0,       -- loot is out of scope; the chest is the reward
    merchant_id    = 0;

DELETE FROM npc_types WHERE id = 2000301;
INSERT INTO npc_types SELECT * FROM tmp_delve_boss;
DROP TEMPORARY TABLE tmp_delve_boss;

-- ---------------------------------------------------------------- mode / zone definition tables
-- The 36 tasks and 72 activities are generated by cross joining these two, rather than written out:
-- hand-listing them is how the goalcount ladder and the mode offsets drift apart.
DROP TEMPORARY TABLE IF EXISTS tmp_delve_mode;
CREATE TEMPORARY TABLE tmp_delve_mode (
    moff      INT,            -- task id offset; must match M.MODES.taskoff
    mname     VARCHAR(32),
    goalmul   DECIMAL(5,2),   -- multiplies the zone's base trash count
    bosses    INT,            -- goalcount of the boss activity
    dur       INT             -- tasks.duration; only Onslaught differs
);
