UNION ALL
SELECT 'activities', COUNT(*)              FROM task_activities WHERE taskid BETWEEN 2000300 AND 2000359
UNION ALL
SELECT 'boss npc',   COUNT(*)              FROM npc_types       WHERE id = 2000301;
